// The build tools' libraries: canonical serialisation (D14), the little-endian writer, generated-file headers.
import { describe, expect, it } from 'vitest';
import { ByteReader, ByteWriter } from './bytes.ts';
import { canonicalJson, compareCodeUnits, compareTuples, sortedEntries } from './canonical.ts';
import { headerProblem, parseHeader, withHeader } from './generated.ts';
import { fromHex, sha256Hex, toHex } from './hash.ts';

describe('canonical', () => {
  it('sorts keys by code units at every level', () => {
    expect(canonicalJson({ b: 1, a: { d: [3, { z: 0, y: 1 }], c: null } }, 0)).toBe(
      '{"a":{"c":null,"d":[3,{"y":1,"z":0}]},"b":1}',
    );
    expect(canonicalJson({ é: 1, z: 2, Z: 3 }, 0)).toBe('{"Z":3,"z":2,"é":1}');
    expect(canonicalJson({ a: 1 })).toBe('{\n  "a": 1\n}\n');
  });
  it('refuses values JSON would silently change', () => {
    expect(() => canonicalJson({ a: Number.NaN })).toThrow('non-finite');
    expect(() => canonicalJson({ a: () => 1 })).toThrow('cannot serialise');
    expect(canonicalJson({ a: undefined, b: 1 }, 0)).toBe('{"b":1}');
  });
  it('compares by code units and tuples element-wise', () => {
    expect(['b', 'a', 'B', 'ä'].sort(compareCodeUnits)).toEqual(['B', 'a', 'b', 'ä']);
    expect(compareTuples(['a', 2], ['a', 10])).toBeLessThan(0);
    expect(compareTuples(['a'], ['a', 1])).toBeLessThan(0);
    expect(sortedEntries({ b: 2, a: 1 })).toEqual([
      ['a', 1],
      ['b', 2],
    ]);
  });
});

describe('bytes', () => {
  it('writes little-endian, pads and reads back', () => {
    const w = new ByteWriter(2);
    w.u8(1).u16(0x0302).u32(0x07060504).pad(8).f64(1.5).i32(-2).str16('§x').bool(true);
    const b = w.finish();
    expect([...b.subarray(0, 8)]).toEqual([1, 2, 3, 4, 5, 6, 7, 0]);
    const r = new ByteReader(b);
    expect([r.u8(), r.u16(), r.u32()]).toEqual([1, 0x0302, 0x07060504]);
    r.take(1);
    expect([r.f64(), r.i32(), r.str16(), r.u8()]).toEqual([1.5, -2, '§x', 1]);
    expect(r.remaining).toBe(0);
  });
  it('refuses out-of-range integers', () => {
    expect(() => new ByteWriter().u8(256)).toThrow('u8 out of range');
    expect(() => new ByteWriter().u16(-1)).toThrow();
    expect(() => new ByteWriter().u32(1.5)).toThrow();
  });
});

describe('generated-file headers (10 §15.1)', () => {
  const text = withHeader(
    {
      generator: 'scripts/schema-gen.ts',
      source: 'schema/',
      command: 'npm run gen',
      schemaHash: '0'.repeat(64),
    },
    'pub const X: u8 = 1;\n',
  );
  it('round-trips', () => {
    const h = parseHeader(text);
    expect(h?.generator).toBe('scripts/schema-gen.ts');
    expect(h?.schemaHash).toBe('0'.repeat(64));
    expect(h?.contentHash).toBe(sha256Hex('pub const X: u8 = 1;\n'));
    expect(headerProblem(text)).toBeNull();
  });
  it('catches a hand edit, a missing header and an unknown generator', () => {
    expect(headerProblem(text.replace('= 1', '= 2'))).toMatch('content hash mismatch');
    expect(headerProblem('pub const X: u8 = 1;\n')).toMatch('missing');
    expect(headerProblem(text.replace('scripts/schema-gen.ts', 'scripts/other.ts'))).toMatch(
      'unknown generator',
    );
    const toml = withHeader(
      { generator: 'scripts/data-stage.ts', source: 'x', command: 'npm run data', comment: '#' },
      'a = 1\n',
    );
    expect(toml.startsWith('# @generated by scripts/data-stage.ts')).toBe(true);
    expect(headerProblem(toml)).toBeNull();
  });
  it('converts hex both ways', () => {
    expect(toHex(fromHex('00ff10'))).toBe('00ff10');
    expect(() => fromHex('0g')).toThrow();
  });
});
